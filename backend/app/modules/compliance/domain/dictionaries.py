@dataclass(frozen=True)
class DictionaryEntry:
    code: str
    label: str
    description: str = ""
    terminal: bool = False

    def to_api(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "label": self.label,
            "description": self.description,
            "terminal": self.terminal,
        }


def _entries(
    *items: tuple[str, str, str] | tuple[str, str, str, bool],
) -> tuple[DictionaryEntry, ...]:
    return tuple(DictionaryEntry(*item) for item in items)


