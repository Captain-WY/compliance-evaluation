def historical_canonical_inspection_plan_dictionary_code(
    value: str,
    *,
    category: str,
) -> str:
    """Reference-scan helper only; not a runtime input compatibility mapper."""
    trimmed = value.strip()
    return INSPECTION_PLAN_HISTORICAL_CODE_MAPS.get(category, {}).get(trimmed, trimmed)


def legacy_codes_for_inspection_plan_dictionary(
    *,
    category: str,
    canonical_code: str,
) -> tuple[str, ...]:
    legacy_map = INSPECTION_PLAN_HISTORICAL_CODE_MAPS.get(category, {})
    normalized = historical_canonical_inspection_plan_dictionary_code(
        canonical_code,
        category=category,
    )
    return tuple(
        legacy_code
        for legacy_code, mapped_code in legacy_map.items()
        if mapped_code == normalized
    )


def reference_codes_for_inspection_plan_dictionary(
    *,
    category: str,
    dict_code: str,
    ui_meta: dict | None,
) -> set[str]:
    normalized = historical_canonical_inspection_plan_dictionary_code(
        dict_code,
        category=category,
    )
    codes = {dict_code, normalized}
    codes.update(
        legacy_codes_for_inspection_plan_dictionary(
            category=category,
            canonical_code=normalized or dict_code,
        )
    )
    legacy_codes = (ui_meta or {}).get("legacyCodes")
    if isinstance(legacy_codes, list):
        codes.update(str(code).strip() for code in legacy_codes if str(code).strip())
    return {code for code in codes if code}


